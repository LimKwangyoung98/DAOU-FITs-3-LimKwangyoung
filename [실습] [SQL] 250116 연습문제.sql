--1. 직원과 부서 정보 조회
--직원 이름과 소속 부서의 근무지를 조회하세요.
SELECT E.NAME, D.LOCATION
FROM EMPLOYEES E
LEFT OUTER JOIN DEPARTMENTS D
  ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;

--2. 직원과 매니저 정보 조회
--직원 이름과 해당 직원의 매니저 이름을 조회하세요. (단, 매니저가 없는 직원도 출력)
SELECT E1.NAME AS EMPLOYEE, E2.NAME AS MANAGER
FROM EMPLOYEES E1
LEFT OUTER JOIN EMPLOYEES E2
  ON E1.MANAGER_ID = E2.EMPLOYEE_ID;

--3. 직원과 급여 정보 조회
--직원 이름과 급여를 조회하되 급여가 NULL인 경우 N/A로 출력하세요.  
SELECT NAME, NVL(TO_CHAR(SALARY), 'N/A') AS SALARY
FROM EMPLOYEES;

SELECT NAME, NVL2(SALARY, TO_CHAR(SALARY), 'N/A') AS SALARY
FROM EMPLOYEES;

--4. 특정 부서 직원 조회
--근무지가 Chicago인 직원 이름과 급여를 조회하세요.
SELECT E.NAME, E.SALARY
FROM EMPLOYEES E, DEPARTMENTS D
WHERE E.DEPARTMENT_ID = D.DEPARTMENT_ID
  AND D.LOCATION = 'Chicago';

--5. 특정 급여 범위 조회
--급여가 5000 이상 10000 이하인 직원의 이름과 급여, 부서명을 조회하세요.
SELECT E.NAME, E.SALARY, D.DEPARTMENT_NAME
FROM EMPLOYEES E
LEFT OUTER JOIN DEPARTMENTS D
  ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
    AND E.SALARY BETWEEN 5000 AND 10000;
    
--6. 최근 3개월 내 입사한 직원
--최근 3개월 이내 입사한 직원 이름과 입사일을 조회하시오.
SELECT NAME, HIRE_DATE
FROM EMPLOYEES
WHERE MONTHS_BETWEEN(SYSDATE, HIRE_DATE) <= 3;

SELECT NAME, HIRE_DATE
FROM EMPLOYEES
WHERE HIRE_DATE >= SYSDATE - (INTERVAL '3' MONTH);

--7. 부서장 이름 조회
--각 부서의 부서장 이름과 부서 이름을 조회하세요.
SELECT D.DEPARTMENT_NAME, E.NAME

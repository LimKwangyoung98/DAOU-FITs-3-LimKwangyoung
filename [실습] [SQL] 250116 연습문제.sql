--16. 특정 지점의 대출 합계
--Branch 8 지점의 대출 총합을 조회하세요. (단, 소수점 아래는 버림)
SELECT B.NAME, FLOOR(SUM(L.AMOUNT)) TOTAL_AMOUNT
FROM BRANCHES B, LOANS L
WHERE B.BRANCH_ID = L.BRANCH_ID AND B.NAME = 'Branch 8'
GROUP BY B.NAME;

--17. 직무별 직원의 평균 급여와 급여 등급 조회
--직무별 직원의 평균 급여를 계산하여 평균 급여가 5000 이상인 경우만 출력합니다. 평균 급여가 8000 이상인 경우 "HIGH", 6000 이상 8000 미만인 경우 "MEDIUM", 6000 미만인 경우 "LOW"로 표시합니다. 결과는 평균 급여가 높은 순으로 정렬하세요.
SELECT JOB_ID, ROUND(AVG(SALARY), 2) AVG_SALARY,
  CASE
    WHEN AVG(SALARY) >= 8000 THEN 'HIGH'
    WHEN AVG(SALARY) >= 6000 THEN 'MEDIUM'
    ELSE 'LOW'
  END SALARY_LEVEL
FROM EMPLOYEES
GROUP BY JOB_ID
HAVING AVG(SALARY) >= 5000
ORDER BY AVG_SALARY DESC;

--18. 고객별 거래 내역
--고객 이름과 총 거래 내역(금액)을 조회하여 고객 이름을 오름차순 하세요.
SELECT C.NAME, NVL(SUM(T.AMOUNT), 0) TOTAL_AMOUNT
FROM CUSTOMERS C
LEFT OUTER JOIN ACCOUNTS A
  ON C.CUSTOMER_ID = A.CUSTOMER_ID
LEFT OUTER JOIN TRANSACTIONS T
  ON A.ACCOUNT_ID = T.ACCOUNT_ID
GROUP BY C.NAME
ORDER BY TO_NUMBER(SUBSTR(C.NAME, 10, LENGTH(C.NAME)));

--19. 부서별 직원의 평균 입사일 차이
--부서별로 평균 근속일을 계산하여 부서 이름으로 오름차순 정렬하세요. (단, 평균 근속일은 반올림하여 정수로 표현)
SELECT D.DEPARTMENT_NAME, NVL(ROUND(AVG(SYSDATE - E.HIRE_DATE)), 0) AVG_DAYS
FROM DEPARTMENTS D
LEFT OUTER JOIN EMPLOYEES E
  ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
ORDER BY TO_NUMBER(SUBSTR(D.DEPARTMENT_NAME, 12, LENGTH(D.DEPARTMENT_NAME)));

--20. 대출 금액 상위 5명 고객 조회
--대출 금액이 가장 높은 상위 5명의 고객의 이름과 대출 금액을 조회하세요. (단, 대출 금액이 동일한 경우 고객의 이름으로 오름차순)
SELECT *
FROM (
  SELECT C.NAME, SUM(L.AMOUNT) TOTAL_AMOUNT
  FROM CUSTOMERS C, LOANS L
  WHERE C.CUSTOMER_ID = L.CUSTOMER_ID
  GROUP BY C.NAME, C.CUSTOMER_ID  --동명이인이 있을 수 있으므로 CUSTOMER_ID로 GROUP BY를 사용해야 하며, NAME과 함께 사용할 수 있다.
  ORDER BY TOTAL_AMOUNT DESC, TO_NUMBER(SUBSTR(C.NAME, 10, LENGTH(C.NAME)))
)
WHERE ROWNUM <= 5;